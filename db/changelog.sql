--changeset paperlane:002-auth-users-and-sessions dbms:postgresql splitStatements:true
CREATE SCHEMA paperlane_auth;

CREATE TABLE paperlane_auth.app_users (
    id UUID PRIMARY KEY,
    issuer TEXT NOT NULL,
    subject TEXT NOT NULL,
    display_name TEXT,
    account_schema TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    disabled_at TIMESTAMPTZ,
    UNIQUE (issuer, subject),
    CHECK (account_schema ~ '^paperlane(_u_[0-9a-f]{32})?$')
);

CREATE TABLE paperlane_auth.sessions (
    token_hash TEXT PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES paperlane_auth.app_users(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CHECK (token_hash ~ '^[0-9a-f]{64}$')
);

CREATE INDEX sessions_user_active_idx ON paperlane_auth.sessions (user_id, expires_at)
    WHERE revoked_at IS NULL;

REVOKE ALL ON SCHEMA paperlane_auth FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA paperlane_auth FROM PUBLIC;
